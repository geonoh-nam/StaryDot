export function koreanForSeries(seriesId, months, nth = 0) {
  const bank = seriesId === 'tayo' ? KOREAN_TAYO_4
    : seriesId === 'teenieping' ? KOREAN_TEENIEPING_7
    : koreanPoolFor(months);
  return bank[nth % bank.length];
}
